// Helpers shared by the public list and the admin page.

async function fetchJson(url, options) {
  const response = await fetch(url, { cache: "no-store", ...options });
  const body = await response.json().catch(() => null);
  if (!response.ok) {
    const error = new Error((body && body.error) || `HTTP ${response.status}`);
    error.status = response.status;
    throw error;
  }
  return body;
}

function loadGameData() {
  return fetchJson("/game-data.json");
}

// "2026.11.05. 14:32" in Budapest time.
function formatDateTime(date) {
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat("hu-HU", {
      timeZone: "Europe/Budapest",
      year: "numeric", month: "2-digit", day: "2-digit",
      hour: "2-digit", minute: "2-digit", hourCycle: "h23",
    }).formatToParts(date).map((p) => [p.type, p.value]),
  );
  return `${parts.year}.${parts.month}.${parts.day}. ${parts.hour}:${parts.minute}`;
}

// Short Hungarian relative time: "épp most", "5 perce", "3 órája", "tegnap", "4 napja", "2 hete", "3 hónapja", "1 éve".
function formatRelative(date, now = new Date()) {
  const minutes = Math.floor((now - date) / 60000);
  if (minutes < 1) return "épp most";
  if (minutes < 60) return `${minutes} perce`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) return `${hours} órája`;
  const days = Math.floor(hours / 24);
  if (days === 1) return "tegnap";
  if (days < 7) return `${days} napja`;
  if (days < 30) return `${Math.floor(days / 7)} hete`;
  if (days < 365) return `${Math.floor(days / 30)} hónapja`;
  return `${Math.floor(days / 365)} éve`;
}

// Footer: "v1.0.0 · kiadva: 2026.11.05. 14:32" (release time shown in Budapest time).
// version.json is generated by deploy.sh, so the footer stays hidden in local development.
async function renderFooter() {
  const footer = document.getElementById("site-footer");
  if (!footer) return;
  try {
    const { version, released } = await fetchJson("/version.json");
    footer.textContent = `v${version} · kiadva: ${formatDateTime(new Date(released))}`;
    footer.hidden = false;
  } catch (error) {
    // No version.json (local development): leave the footer hidden.
  }
}

renderFooter();

function loadCharacters() {
  return fetchJson("/api/characters");
}

function sortCharacters(characters) {
  return characters.sort((a, b) => b.level - a.level || a.name.localeCompare(b.name, "hu"));
}

function cell(text, className) {
  const td = document.createElement("td");
  td.textContent = text;
  if (className) td.className = className;
  return td;
}

// An icon with its English name shown as a tooltip on hover.
function icon(src, name) {
  const wrapper = document.createElement("span");
  wrapper.className = "icon";
  wrapper.dataset.tooltip = name;
  const img = document.createElement("img");
  img.src = src;
  img.alt = name;
  img.width = 28;
  img.height = 28;
  wrapper.append(img);
  return wrapper;
}

function iconCell(src, name) {
  const td = document.createElement("td");
  td.append(icon(src, name));
  return td;
}

// Relative time with the exact time as a tooltip, e.g. "3 órája" (hover: "2026.11.05. 13:40").
function relativeTime(iso) {
  const date = new Date(iso);
  const span = document.createElement("span");
  span.className = "tooltip";
  span.dataset.tooltip = formatDateTime(date);
  span.textContent = formatRelative(date);
  return span;
}

// Last login from the Blizzard API; "—" while the API does not know the character.
function lastLoginCell(lastLogin) {
  const td = document.createElement("td");
  td.className = "last-login";
  if (lastLogin) td.append(relativeTime(lastLogin));
  else td.textContent = "—";
  return td;
}

function professionsCell(professions, gameData) {
  const td = document.createElement("td");
  const list = document.createElement("span");
  list.className = "icon-list";
  for (const key of professions || []) {
    const profession = gameData.professions[key];
    if (!profession) continue; // e.g. a profession no longer offered
    list.append(icon(`/icons/profession/${key}.jpg`, profession.name));
  }
  td.append(list);
  return td;
}

// renderActions (optional) returns a <td> appended at the end of the row, e.g. admin buttons.
function renderCharacterRow(character, gameData, renderActions) {
  const cls = gameData.classes[character.class] || { name: character.class, color: null };
  const raceName = gameData.races[character.race] || character.race;
  const gender = character.gender === "female" ? "female" : "male";
  const tr = document.createElement("tr");
  tr.dataset.id = character.id;
  if (cls.color) tr.style.setProperty("--class-color", cls.color);

  const factionName = gameData.factions[character.faction];
  tr.append(
    cell(`${character.name} ${character.surname}`, "name"),
    cell(character.owner || "", "owner"),
    factionName ? iconCell(`/icons/faction/${character.faction}.jpg`, factionName) : cell(""),
    iconCell(`/icons/class/${character.class}.jpg`, cls.name),
    cell(String(character.level), "num"),
    iconCell(`/icons/race/${character.race}_${gender}.jpg`, raceName),
    professionsCell(character.professions, gameData),
  );

  const roleTd = document.createElement("td");
  if (character.role) {
    const role = document.createElement("span");
    role.className = `role role-${character.role}`;
    role.textContent = gameData.roles[character.role] || character.role;
    roleTd.append(role);
  }
  tr.append(roleTd, lastLoginCell(character.lastLogin));

  if (renderActions) tr.append(renderActions(character));
  return tr;
}

function showTableMessage(tbody, text) {
  const td = cell(text, "empty");
  td.colSpan = tbody.closest("table").tHead.rows[0].cells.length;
  const tr = document.createElement("tr");
  tr.append(td);
  tbody.replaceChildren(tr);
}

// Fills the character table and the count label; returns the loaded characters.
// With keepOnError (background refresh) a failed load leaves the current table as it is.
async function renderCharacterTable(tbody, countEl, gameData, renderActions, { keepOnError = false } = {}) {
  try {
    const characters = sortCharacters(await loadCharacters());
    if (characters.length === 0) {
      showTableMessage(tbody, "Még nincs karakter a listán.");
    } else {
      tbody.replaceChildren(...characters.map((c) => renderCharacterRow(c, gameData, renderActions)));
    }
    countEl.textContent = `${characters.length} karakter`;
    return characters;
  } catch (error) {
    console.error("Failed to load characters", error);
    if (!keepOnError) showTableMessage(tbody, "Nem sikerült betölteni a karaktereket.");
    return [];
  }
}

// Calls refresh every intervalMs while the page is visible, and right away when it becomes visible again,
// so the list and the "Frissítve" times stay current without reloading the page.
function startAutoRefresh(refresh, intervalMs = 60_000) {
  let timer = null;
  const start = () => {
    if (timer === null) timer = setInterval(refresh, intervalMs);
  };
  const stop = () => {
    clearInterval(timer);
    timer = null;
  };
  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      stop();
    } else {
      refresh();
      start();
    }
  });
  if (!document.hidden) start();
}
